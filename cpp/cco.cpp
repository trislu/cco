std::string render(std::string_view tmpl,
                   const std::map<std::string, std::string> &vars) {
    std::string out;
    size_t i = 0;
    while (i < tmpl.size()) {
        if (tmpl[i] == '{' && i + 1 < tmpl.size() && tmpl[i + 1] == '{') {
            size_t end = tmpl.find("}}", i + 2);
            if (end != std::string_view::npos) {
                std::string key(tmpl.substr(i + 2, end - (i + 2)));
                auto it = vars.find(key);
                if (it != vars.end()) {
                    out += it->second;
                    i = end + 2;
                    continue;
                }
            }
        }
        out += tmpl[i++];
    }
    return out;
}

bool path_exists(const fs::path &p) {
    std::error_code ec;
    return fs::exists(p, ec);
}

bool path_is_regular(const fs::path &p) {
    std::error_code ec;
    return fs::is_regular_file(p, ec);
}

bool bootstrap_build(const fs::path &dir, const Toolchain &tc, bool echo) {
    std::vector<std::string> cmd;
    if (tc.is_msvc()) {
        cmd = {tc.cxx,
               "/nologo",
               "/std:c++17",
               "/O2",
               "/Fe:" + (dir / "build.exe").string(),
               "build.cpp"};
    } else {
        cmd = {tc.cxx,     "-std=c++17", "-O2", "-o", (dir / "build").string(),
               "build.cpp"};
    }
    if (run_program(cmd, RunOptions{dir, echo}) != 0)
        return false;
    fs::path exe = dir / (tc.is_msvc() ? "build.exe" : "build");
    return run_program({exe.string()}, RunOptions{dir, echo}) == 0;
}

