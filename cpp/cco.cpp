bool valid_name(const std::string &name, std::string &err) {
    if (name.empty()) {
        err = "name is empty";
        return false;
    }
    if (name == "." || name == "..") {
        err = "name cannot be `.` or `..`";
        return false;
    }
    if (name.front() == '-') {
        err = "name cannot start with `-`";
        return false;
    }
    if (name.back() == '.' || name.back() == ' ') {
        err = "name cannot end with `.` or space";
        return false;
    }
    for (char c : name) {
        unsigned char uc = static_cast<unsigned char>(c);
        if (!(std::isalnum(uc) || c == '_' || c == '-' || c == '.')) {
            err = "name may only contain A-Z, a-z, 0-9, `_`, `-`, `.`";
            return false;
        }
    }

    std::string base = name;
    size_t dot = base.find('.');
    if (dot != std::string::npos)
        base = base.substr(0, dot);
    std::transform(base.begin(), base.end(), base.begin(), [](unsigned char c) {
        return static_cast<char>(std::toupper(c));
    });
    static const std::set<std::string> reserved = {
        "CON",  "PRN",  "AUX",  "NUL",  "COM1", "COM2", "COM3", "COM4",
        "COM5", "COM6", "COM7", "COM8", "COM9", "LPT1", "LPT2", "LPT3",
        "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9"};
    if (reserved.count(base)) {
        err = "`" + name + "` is a Windows reserved name";
        return false;
    }
    return true;
}

std::string ident_from_name(const std::string &name) {
    std::string out;
    for (char c : name) {
        unsigned char uc = static_cast<unsigned char>(c);
        if (std::isalnum(uc) || c == '_')
            out += c;
        else
            out += '_';
    }
    if (out.empty())
        out = "app";
    if (std::isdigit(static_cast<unsigned char>(out[0])))
        out = "_" + out;
    return out;
}

fs::path executable_path(const char *argv0) {
#ifdef _WIN32
    wchar_t buf[4096];
    DWORD n = GetModuleFileNameW(
        nullptr, buf, static_cast<DWORD>(sizeof(buf) / sizeof(buf[0])));
    if (n > 0 && n < sizeof(buf) / sizeof(buf[0]))
        return fs::path(std::wstring(buf, n));
#elif defined(__APPLE__)
    uint32_t size = 0;
    _NSGetExecutablePath(nullptr, &size);
    if (size > 0) {
        std::vector<char> buf(size + 1);
        if (_NSGetExecutablePath(buf.data(), &size) == 0)
            return fs::path(buf.data());
    }
#elif defined(__linux__)
    char buf[4096];
    ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
    if (n > 0) {
        buf[n] = '\0';
        return fs::path(buf);
    }
#endif
    return fs::absolute(argv0);
}

fs::path resolve_header(const std::string &explicit_path, const char *argv0) {
    if (!explicit_path.empty())
        return fs::path(explicit_path);
    std::vector<fs::path> candidates;
    candidates.emplace_back(CCO_HEADER_FILE);
    if (argv0 && *argv0) {
        std::error_code ec;
        fs::path exe = executable_path(argv0);
        if (!ec) {
            fs::path dir = exe.parent_path();
            candidates.push_back(dir / "cco.hpp");
            candidates.push_back(dir / "cpp" / "cco.hpp");
            candidates.push_back(dir / ".." / "include" / "cco.hpp");
            candidates.push_back(dir / ".." / "include" / "cco" / "cco.hpp");
            candidates.push_back(dir / ".." / "share" / "cco" / "cco.hpp");
            candidates.push_back(dir / ".." / "cco.hpp");
            candidates.push_back(dir / ".." / "cpp" / "cco.hpp");
            candidates.push_back(dir / ".." / ".." / "cco.hpp");
        }
    }
    std::error_code ec;
    candidates.push_back(fs::current_path(ec) / "cco.hpp");
    candidates.push_back(fs::current_path(ec) / "cpp" / "cco.hpp");
    for (const auto &c : candidates) {
        if (path_is_regular(c))
            return c;
    }
    return {};
}

bool same_content(const fs::path &path, std::string_view content) {
    std::string existing;
    if (!read_file(path, existing))
        return false;
    return existing == content;
}

void print_next_steps(const fs::path &dir, bool lib, bool quiet) {
    if (quiet)
        return;
    std::fprintf(stdout, "\nNext:\n");
    if (dir != fs::current_path())
        std::fprintf(stdout, "  cd %s\n", dir.string().c_str());
#ifdef _WIN32
    std::fprintf(stdout,
                 "  cl /nologo /std:c++17 /O2 /Fe:build.exe build.cpp\n");
    std::fprintf(stdout, "  build%s\n", lib ? " test" : "");
#else
    std::fprintf(stdout, "  c++ -std=c++17build.cpp -o build\n");
    std::fprintf(stdout, "  ./build%s\n", lib ? " test" : "");
#endif
}

