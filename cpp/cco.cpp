int init_main(int argc, char **argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: %s new|init [path] [options]\n", argv[0]);
        return 2;
    }
    if (argc == 2 &&
        (std::string(argv[1]) == "--help" || std::string(argv[1]) == "-h")) {
        std::fprintf(stdout,
                     "usage: %s new|init [path] [options]\n"
                     "  see `%s new --help` for the full option list\n",
                     argv[0], argv[0]);
        return 0;
    }
    std::string command = argv[1];
    if (command != "new" && command != "init") {
        std::fprintf(stderr, "cco: expected `new` or `init`, got `%s`\n",
                     command.c_str());
        return 2;
    }

    bool lib = false;
    bool bin = false;
    bool ide = false;
    bool build = false;
    bool dry = false;
    bool force = false;
    bool quiet = false;
    std::string name;
    std::string vcs = "none";
    std::string header_path;
    std::string path_arg;

    for (int i = 2; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "--lib") {
            lib = true;
        } else if (a == "--bin") {
            bin = true;
        } else if (a == "--ide") {
            ide = true;
        } else if (a == "--build") {
            build = true;
        } else if (a == "--dry-run") {
            dry = true;
        } else if (a == "--force") {
            force = true;
        } else if (a == "--quiet" || a == "-q") {
            quiet = true;
        } else if (a == "--name") {
            if (i + 1 >= argc) {
                std::fprintf(stderr, "cco: --name expects a value\n");
                return 2;
            }
            name = argv[++i];
        } else if (a == "--vcs") {
            if (i + 1 >= argc) {
                std::fprintf(stderr, "cco: --vcs expects a value\n");
                return 2;
            }
            vcs = argv[++i];
        } else if (a == "--cco-header") {
            if (i + 1 >= argc) {
                std::fprintf(stderr, "cco: --cco-header expects a value\n");
                return 2;
            }
            header_path = argv[++i];
        } else if (a == "--help" || a == "-h") {
            std::fprintf(
                stdout,
                "usage: %s %s [path] [options]\n"
                "  --bin | --lib      executable (default) or library "
                "template\n"
                "  --name <name>      target name (default: directory name)\n"
                "  --vcs none|git     version control (default: none)\n"
                "  --ide             write .bsp/compiler-only.json\n"
                "  --build           compile build.cpp and run it once\n"
                "  --dry-run         print the plan without writing\n"
                "  --force           overwrite scaffold files\n"
                "  --quiet            suppress file/next-step output\n"
                "  --cco-header <path>  cco.hpp to vendor\n",
                argv[0], command.c_str());
            return 0;
        } else if (!a.empty() && a[0] == '-') {
            std::fprintf(stderr, "cco: unknown option: %s\n", a.c_str());
            return 2;
        } else {
            if (!path_arg.empty()) {
                std::fprintf(stderr, "cco: unexpected argument: %s\n",
                             a.c_str());
                return 2;
            }
            path_arg = a;
        }
    }

    if (lib && bin) {
        std::fprintf(stderr, "cco: --lib and --bin are mutually exclusive\n");
        return 2;
    }
    if (vcs != "none" && vcs != "git") {
        std::fprintf(stderr, "cco: --vcs must be `none` or `git`\n");
        return 2;
    }

    std::error_code ec;
    fs::path target;
    if (command == "new") {
        if (path_arg.empty()) {
            std::fprintf(stderr, "cco: new expects a path\n");
            return 2;
        }
        target = fs::absolute(path_arg, ec);
        if (ec)
            target = path_arg;
        if (path_exists(target)) {
            std::fprintf(stderr, "cco: `%s` already exists; use `init`\n",
                         target.string().c_str());
            return 1;
        }
    } else {
        target = path_arg.empty() ? fs::current_path(ec)
                                  : fs::absolute(path_arg, ec);
        if (ec)
            target = path_arg;
        if (!path_exists(target)) {
            std::fprintf(stderr, "cco: `%s` does not exist; use `new`\n",
                         target.string().c_str());
            return 1;
        }
        if (!fs::is_directory(target, ec)) {
            std::fprintf(stderr, "cco: `%s` is not a directory\n",
                         target.string().c_str());
            return 1;
        }
    }

    if (name.empty()) {
        name = target.filename().string();
        if (name.empty())
            name = target.parent_path().filename().string();
    }
    std::string name_err;
    if (!valid_name(name, name_err)) {
        std::fprintf(stderr, "cco: invalid name `%s`: %s\n", name.c_str(),
                     name_err.c_str());
        return 1;
    }
    std::string ident = ident_from_name(name);

    fs::path header = resolve_header(header_path, argv[0]);
    std::string header_content;
    if (header.empty() || !read_file(header, header_content)) {
        std::fprintf(
            stderr,
            "cco: cannot find cco.hpp; pass --cco-header /path/to/cco.hpp\n");
        return 1;
    }

    std::map<std::string, std::string> vars = {
        {"name", name},
        {"ident", ident},
        {"version", CCO_VERSION},
    };

    std::vector<PlannedFile> files;
    files.push_back({target / "cco.hpp", header_content});
    files.push_back(
        {target / "build.cpp", render(lib ? kLibBuild : kAppBuild, vars)});
    files.push_back({target / ".gitignore", std::string(kGitignore)});
    files.push_back(
        {target / "README.md", render(lib ? kReadmeLib : kReadmeApp, vars)});
    files.push_back({target / "compile_flags.txt",
                     std::string(lib ? kCompileFlagsLib : kCompileFlags)});
    if (lib) {
        files.push_back({target / "include" / ident / (ident + ".h"),
                         render(kLibHeader, vars)});
        files.push_back(
            {target / "src" / (ident + ".cpp"), render(kLibSource, vars)});
        files.push_back(
            {target / "tests" / (ident + "_test.cpp"), render(kLibTest, vars)});
    } else {
        files.push_back({target / "src" / "main.cpp", render(kAppMain, vars)});
    }
    if (ide) {
        std::string build_argv = "build.exe";
#ifndef _WIN32
        build_argv = "./build";
#endif
        std::string bsp = "{\n"
                          "  \"name\": \"compiler-only\",\n"
                          "  \"version\": \"" +
                          std::string(CCO_VERSION) +
                          "\",\n"
                          "  \"bspVersion\": \"2.2.0\",\n"
                          "  \"languages\": [\"cpp\", \"c\"],\n"
                          "  \"argv\": [\"" +
                          build_argv +
                          "\", \"bsp\"]\n"
                          "}\n";
        files.push_back({target / ".bsp" / "compiler-only.json", bsp});
    }

    bool conflict = false;
    std::vector<PlannedFile> to_write;
    for (const auto &f : files) {
        if (!path_exists(f.path)) {
            to_write.push_back(f);
            continue;
        }
        std::error_code rel_ec;
        fs::path rel = fs::relative(f.path, target, rel_ec);
        std::string rels =
            rel_ec ? f.path.generic_string() : rel.generic_string();
        bool user_source = rels.rfind("src/", 0) == 0 ||
                           rels.rfind("include/", 0) == 0 ||
                           rels.rfind("tests/", 0) == 0;
        if (user_source) {
            if (!quiet)
                std::fprintf(stdout, "! %s (source exists, skipped)\n",
                             f.path.string().c_str());
            continue;
        }
        std::string base = f.path.filename().string();
        if (base == "cco.hpp") {
            if (same_content(f.path, f.content)) {
                if (!quiet)
                    std::fprintf(stdout, "= %s (up to date)\n",
                                 f.path.string().c_str());
                continue;
            }
            if (!force) {
                std::fprintf(stderr,
                             "cco: `%s` exists with different content (use "
                             "--force to overwrite)\n",
                             f.path.string().c_str());
                conflict = true;
                continue;
            }
        }
        if (!force) {
            if (base == "build.cpp") {
                std::fprintf(
                    stderr,
                    "cco: `%s` already exists (use --force to overwrite)\n",
                    f.path.string().c_str());
                conflict = true;
            } else {
                if (!quiet)
                    std::fprintf(stdout, "! %s (exists, skipped)\n",
                                 f.path.string().c_str());
            }
            continue;
        }
        to_write.push_back(f);
    }
    if (conflict)
        return 1;

    if (dry) {
        for (const auto &f : to_write) {
            if (!quiet)
                std::fprintf(stdout, "+ %s\n", f.path.string().c_str());
        }
        return 0;
    }

    if (command == "new") {
        fs::create_directories(target, ec);
        if (ec) {
            std::fprintf(stderr, "cco: cannot create %s: %s\n",
                         target.string().c_str(), ec.message().c_str());
            return 1;
        }
    }

    for (const auto &f : to_write) {
        std::string err;
        if (!write_file(f.path, f.content, err)) {
            std::fprintf(stderr, "cco: %s\n", err.c_str());
            return 1;
        }
        if (!quiet)
            std::fprintf(stdout, "+ %s\n", f.path.string().c_str());
    }

    if (vcs == "git") {
        if (path_exists(target / ".git")) {
            if (!quiet)
                std::fprintf(stdout, "= .git (already initialized)\n");
        } else {
            int rc =
                run_program({"git", "init", "-q"}, RunOptions{target, false});
            if (rc != 0) {
                std::fprintf(stderr, "cco: warning: `git init` failed (%d)\n",
                             rc);
            }
        }
    }

    Toolchain tc = Toolchain::detect();
    if (build) {
        if (!bootstrap_build(target, tc, false)) {
            std::fprintf(
                stderr, "cco: bootstrap build failed; files are still there\n");
            return 1;
        }
    }

    if (!quiet) {
        std::fprintf(stdout, "\nCreated %s `%s` in %s\n",
                     lib ? "library" : "executable", name.c_str(),
                     target.string().c_str());
    }
    print_next_steps(target, lib, quiet);
    return 0;
}

