    "#define CCO_IMPLEMENTATION\n"
    "#include \"cco.h\"\n"
    "\n"
    "int main(int argc, char **argv) {\n"
    "    CCO_GO_REBUILD_URSELF(argc, argv);\n"
    "    Cco_Workspace ws;\n"
    "    cco_workspace_init(&ws, argc, argv);\n"
    "    cco_workspace_managed_layout(&ws);\n"
    "    Cco_Target *lib = cco_library(&ws, \"%s\");\n"
    "    cco_target_add_source(lib, \"src/%s.c\");\n"
    "    cco_target_add_include(lib, \"include\");\n"
    "    Cco_Target *tests = cco_test(&ws, \"%s_tests\");\n"
    "    cco_target_add_source(tests, \"tests/%s_test.c\");\n"
    "    cco_target_add_include(tests, \"include\");\n"
    "    cco_target_link(tests, lib);\n"
    "    return cco_workspace_run(&ws);\n"
    "}\n";

static const char *kAppMain =
    "#include <stdio.h>\n"
    "\n"
    "int main(void) {\n"
    "    printf(\"hello, cco C\\n\");\n"
    "    return 0;\n"
    "}\n";

static const char *kLibHeader =
    "#ifndef %s_H\n"
    "#define %s_H\n"
    "\n"
    "int %s_value(void);\n"
    "\n"
    "#endif\n";

static const char *kLibSource =
    "#include \"%s/%s.h\"\n"
    "\n"
    "int %s_value(void) { return 42; }\n";

static const char *kLibTest =
    "#include \"%s/%s.h\"\n"
    "#include <stdio.h>\n"
    "\n"
    "int main(void) {\n"
    "    if (%s_value() != 42) {\n"
    "        fprintf(stderr, \"unexpected value\\n\");\n"
    "        return 1;\n"
    "    }\n"
    "    printf(\"OK\\n\");\n"
    "    return 0;\n"
    "}\n";

static const char *kReadme =
    "# %s\n"
    "\n"
    "Generated by `cco`.\n"
    "\n"
    "```sh\n"
    "cc -std=c11 build.c -o build\n"
    "./build\n"
    "```\n";

static const char *kCompileFlags = "-std=c11\n-Iinclude\n";

static char *cco_ident(const char *name) {
    Cco_SB sb = {0};
    for (const char *p = name; *p; ++p) {
        unsigned char c = (unsigned char)*p;
        if (isalnum(c) || c == '_') cco_sb_append_ch(&sb, (char)c);
        else cco_sb_append_ch(&sb, '_');
    }
    if (sb.len == 0) cco_sb_append(&sb, "mylib");
    if (isdigit((unsigned char)sb.data[0])) {
        Cco_SB fixed = {0};
        cco_sb_append(&fixed, "x_");
        cco_sb_append(&fixed, cco_sb_cstr(&sb));
        cco_sb_free(&sb);
        return cco_xstrdup(cco_sb_cstr(&fixed));
    }
    char *out = cco_xstrdup(cco_sb_cstr(&sb));
    cco_sb_free(&sb);
    return out;
}

static bool cco_read_file_text(const char *path, char **out) {
    FILE *f = fopen(path, "rb");
    if (!f) return false;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return false; }
    long n = ftell(f);
    if (n < 0) { fclose(f); return false; }
    rewind(f);
    char *buf = (char *)cco_xmalloc((size_t)n + 1);
    size_t got = fread(buf, 1, (size_t)n, f);
    fclose(f);
    buf[got] = '\0';
    *out = buf;
    return true;
}

static bool cco_write_template(const char *dir, const char *name, const char *content) {
    char *path = cco_path_join(dir, name);
    bool ok = cco_write_file(path, content);
    if (!ok) fprintf(stderr, "cco: cannot write %s\n", path);
    free(path);
    return ok;
}

static char *cco_format(const char *fmt, const char *a, const char *b, const char *c,
                        const char *d) {
    Cco_SB sb = {0};
    /* The templates use at most four string substitutions. */
    const char *p = fmt;
    const char *args[4] = {a, b, c, d};
    int index = 0;
    while (*p) {
        if (p[0] == '%' && p[1] == 's') {
            cco_sb_append(&sb, args[index] ? args[index] : "");
            ++index;
            p += 2;
        } else {
            cco_sb_append_ch(&sb, *p++);
        }
    }
    char *out = cco_xstrdup(cco_sb_cstr(&sb));
    cco_sb_free(&sb);
    return out;
}

static char *cco_pick_header(const char *override, const char *argv0) {
    if (override && *override) return cco_xstrdup(override);

    Cco_Str_Array candidates = {0};
    cco_str_array_push(&candidates, CCO_HEADER_FILE);
    if (argv0 && *argv0) {
        char *exe = cco_executable_path(argv0);
        char *dir = cco_path_parent(exe);
        cco_str_array_push_owned(&candidates, cco_path_join(dir, "cco.h"));
        cco_str_array_push_owned(&candidates, cco_path_join(dir, "c/cco.h"));
        cco_str_array_push_owned(&candidates, cco_path_join(dir, "../include/cco.h"));
        cco_str_array_push_owned(&candidates, cco_path_join(dir, "../include/cco/cco.h"));
        cco_str_array_push_owned(&candidates, cco_path_join(dir, "../share/cco/cco.h"));
        free(dir);
        free(exe);
    }
    char *cwd = cco_path_absolute(".");
    char *c3 = cco_path_join(cwd, "cco.h");
    char *c4 = cco_path_join(cwd, "c/cco.h");
    cco_str_array_push_owned(&candidates, c3);
    cco_str_array_push_owned(&candidates, c4);
    free(cwd);

    char *found = NULL;
    for (size_t i = 0; i < candidates.count; ++i) {
        if (cco_path_is_file(candidates.items[i])) {
            found = cco_xstrdup(candidates.items[i]);
            break;
        }
    }
    cco_str_array_free(&candidates);
    return found;
}

static int cco_scaffold(int argc, char **argv) {
    const char *command = argc > 1 ? argv[1] : "new";
    if (strcmp(command, "new") != 0 && strcmp(command, "init") != 0) {
        fprintf(stderr, "usage: %s new|init [path] [--name N] [--lib|--bin] [--cco-header P]\n",
                argv[0]);
        return 2;
    }
    const char *path = ".";
    const char *name = NULL;
    const char *header = NULL;
    bool lib = false;
    bool force = false;
    bool quiet = false;
    bool build = false;
    for (int i = 2; i < argc; ++i) {
        if (strcmp(argv[i], "--name") == 0 && i + 1 < argc) name = argv[++i];
        else if (strcmp(argv[i], "--lib") == 0) lib = true;
        else if (strcmp(argv[i], "--bin") == 0) lib = false;
        else if (strcmp(argv[i], "--cco-header") == 0 && i + 1 < argc) header = argv[++i];
        else if (strcmp(argv[i], "--force") == 0) force = true;
        else if (strcmp(argv[i], "--quiet") == 0) quiet = true;
        else if (strcmp(argv[i], "--build") == 0) build = true;
        else if (argv[i][0] != '-') path = argv[i];
        else {
            fprintf(stderr, "cco: unknown option: %s\n", argv[i]);
            return 2;
        }
    }
    char *dir = cco_path_absolute(path);
    if (strcmp(command, "new") == 0) {
        if (!cco_path_mkdir_p(dir)) {
            fprintf(stderr, "cco: cannot create %s\n", dir);
            free(dir);
            return 1;
        }
    } else if (!cco_path_is_dir(dir)) {
        fprintf(stderr, "cco: not a directory: %s\n", dir);
        free(dir);
        return 1;
    }

    char *build_path = cco_path_join(dir, "build.c");
    if (!force && cco_path_is_file(build_path)) {
        fprintf(stderr, "cco: %s already exists (use --force)\n", build_path);
        free(build_path);
        free(dir);
        return 1;
    }
    free(build_path);

    char *base = cco_xstrdup(cco_path_basename(dir));
    if (name && *name) {
        free(base);
        base = cco_xstrdup(name);
    }
    char *ident = cco_ident(base);

    char *header_path = cco_pick_header(header, argv[0]);
    if (!header_path) {
        fprintf(stderr, "cco: cannot find cco.h; pass --cco-header /path/to/cco.h\n");
        free(ident);
        free(base);
        free(dir);
        return 1;
    }
    char *header_text = NULL;
    if (!cco_read_file_text(header_path, &header_text)) {
        fprintf(stderr, "cco: cannot read header: %s\n", header_path);
        free(header_path);
        free(ident);
        free(base);
        free(dir);
        return 1;
    }
    free(header_path);
    char *cco_header_dst = cco_path_join(dir, "cco.h");
    bool ok = cco_write_file(cco_header_dst, header_text);
    free(cco_header_dst);
    free(header_text);
    if (!ok) {
        fprintf(stderr, "cco: cannot write cco.h\n");
        free(ident);
        free(base);
        free(dir);
        return 1;
    }

    char *src = cco_path_join(dir, "src");
    cco_path_mkdir_p(src);
    char *main_c = cco_path_join(src, "main.c");
    ok = cco_write_file(main_c, kAppMain);
    free(main_c);
    free(src);
    if (!ok) {
        free(ident);
        free(base);
        free(dir);
        return 1;
    }

    char *build_text = lib ? cco_format(kLibBuild, ident, ident, ident, ident)
                           : cco_format(kAppBuild, ident, ident, ident, ident);
    char *build_dst = cco_path_join(dir, "build.c");
    ok = cco_write_file(build_dst, build_text);
    free(build_dst);
    free(build_text);

    if (lib) {
        char *inc = cco_path_join(dir, "include");
        char *inc_pkg = cco_path_join(inc, ident);
        cco_path_mkdir_p(inc_pkg);
        Cco_SB hpath = {0};
        cco_sb_append(&hpath, ident);
        cco_sb_append(&hpath, ".h");
        char *header_file = cco_path_join(inc_pkg, cco_sb_cstr(&hpath));
        char *header_text2 = cco_format(kLibHeader, ident, ident, ident, ident);
        ok = cco_write_file(header_file, header_text2);
        free(header_text2);
        free(header_file);
        cco_sb_free(&hpath);
        free(inc_pkg);
        free(inc);

        char *lib_src = cco_path_join(dir, "src");
        Cco_SB sfile = {0};
        cco_sb_append(&sfile, ident);
        cco_sb_append(&sfile, ".c");
        char *lib_c = cco_path_join(lib_src, cco_sb_cstr(&sfile));
        char *lib_text = cco_format(kLibSource, ident, ident, ident, ident);
        ok = ok && cco_write_file(lib_c, lib_text);
        free(lib_text);
        free(lib_c);
        cco_sb_free(&sfile);
        free(lib_src);

        char *tests = cco_path_join(dir, "tests");
        cco_path_mkdir_p(tests);
        Cco_SB tfile = {0};
        cco_sb_append(&tfile, ident);
        cco_sb_append(&tfile, "_test.c");
        char *test_c = cco_path_join(tests, cco_sb_cstr(&tfile));
        char *test_text = cco_format(kLibTest, ident, ident, ident, ident);
        ok = ok && cco_write_file(test_c, test_text);
        free(test_text);
        free(test_c);
        cco_sb_free(&tfile);
        free(tests);
    }

    char *readme = cco_format(kReadme, ident, NULL, NULL, NULL);
    ok = ok && cco_write_template(dir, "README.md", readme);
    free(readme);
    ok = ok && cco_write_template(dir, "compile_flags.txt", kCompileFlags);
    ok = ok && cco_write_template(dir, ".gitignore", ".cco/\nbuild\nbuild.exe\nbuild.old\nbin/\nobj/\ncompile_commands.json\n");

    free(ident);
    free(base);

    if (!ok) {
        free(dir);
        return 1;
    }
    if (!quiet) printf("created %s\n", dir);

    if (build) {
        Cco_Str_Array cmd = {0};
        cco_str_array_push(&cmd, "cc");
        cco_str_array_push(&cmd, "-std=c11");
        cco_str_array_push(&cmd, "build.c");
        cco_str_array_push(&cmd, "-o");
        cco_str_array_push(&cmd, "build");
        int rc = cco_run_program(&cmd, dir, false);
        cco_str_array_free(&cmd);
        if (rc != 0) {
            fprintf(stderr, "cco: generated build failed\n");
            free(dir);
            return 1;
        }
        Cco_Str_Array run = {0};
        cco_str_array_push(&run, "./build");
        if (lib) cco_str_array_push(&run, "test");
        rc = cco_run_program(&run, dir, false);
        cco_str_array_free(&run);
        free(dir);
        return rc;
    }
    free(dir);
    return 0;
}

int main(int argc, char **argv) {
    CCO_GO_REBUILD_URSELF(argc, argv);
    if (argc > 1 && (strcmp(argv[1], "new") == 0 || strcmp(argv[1], "init") == 0)) {
        return cco_scaffold(argc, argv);
    }
    fprintf(stderr, "usage: %s new|init [path] [--name N] [--lib|--bin] [--cco-header P] [--force] [--build]\n",
            argv[0]);
    return 2;
}
